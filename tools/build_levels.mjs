#!/usr/bin/env node
/**
 * Compiles reviewed content (content/*.json) + authored layouts (tools/levels/*.mjs)
 * into assets/data/levels/<id>.json, validating each with js/core/LevelSchema.js
 * and the reachability simulations, then writes js/data/GameData.js (menu cards
 * and facts, available before any asset loads).
 *
 * usage: node tools/build_levels.mjs        (exit 1 on any validation failure)
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { ROOT, readJSON } from './levels/common.mjs';
import * as sojourner from './levels/sojourner.mjs';
import * as spirit from './levels/spirit.mjs';
import * as opportunity from './levels/opportunity.mjs';

const require = createRequire(import.meta.url);
const LevelSchema = require(join(ROOT, 'js/core/LevelSchema.js'));

const frameCounts = {
    rover: readJSON('assets/sprites/rover.json').frames.length,
    sojourner: readJSON('assets/sprites/sojourner.json').frames.length,
};

let failed = false;
const levels = {};
for (const mod of [sojourner, spirit, opportunity]) {
    const level = mod.build();
    const errs = LevelSchema.validate(level, { frameCounts });
    if (errs.length) { failed = true; console.log(`✗ ${level.id}: ${errs.length} schema error(s)`); errs.forEach((e) => console.log('    ' + e)); continue; }
    try {
        const report = mod.verify(level);
        console.log(`✓ ${level.id}: schema OK, ${level.world.finishX - level.world.startX} units`);
        report.forEach((l) => console.log('    ' + l));
    } catch (e) { failed = true; console.log(`✗ ${level.id}: ${e.message}`); continue; }
    levels[level.id] = level;
}

// cross-level rules
if (levels.sojourner && levels.spirit && levels.opportunity) {
    const len = (l) => l.world.finishX - l.world.startX;
    const longestOther = Math.max(len(levels.sojourner), len(levels.spirit));
    const ratio = len(levels.opportunity) / longestOther;
    console.log(`  Opportunity length ratio vs longest other: ${ratio.toFixed(2)}x (need >= 1.5)`);
    if (ratio < 1.5) { failed = true; console.log('✗ Opportunity must be >= 1.5x the longer of Sojourner and Spirit'); }
    const sig = (l) => JSON.stringify([l.terrain.ground, l.hazards.map((h) => [h.type, h.x])]);
    if (sig(levels.spirit) === sig(levels.opportunity)) { failed = true; console.log('✗ Opportunity duplicates Spirit geometry'); }
    if (levels.spirit.world.seed === levels.opportunity.world.seed) { failed = true; console.log('✗ duplicate seeds'); }
}
if (failed) { console.log('\nlevel build FAILED'); process.exit(1); }

mkdirSync(join(ROOT, 'assets/data/levels'), { recursive: true });
for (const [id, level] of Object.entries(levels)) writeFileSync(join(ROOT, `assets/data/levels/${id}.json`), JSON.stringify(level, null, 1) + '\n');

const facts = readJSON('content/facts.json');
const missions = Object.values(levels).sort((a, b) => a.order - b.order).map((l) => ({
    id: l.id, order: l.order, title: l.title, subtitle: l.subtitle, ability: l.ability.id,
    url: `assets/data/levels/${l.id}.json`, texture: l.rover.texture,
}));
const soj = readJSON('assets/sprites/sojourner.json');
const textures = { sojourner: { url: soj.image, frameWidth: soj.frameWidth, frameHeight: soj.frameHeight } };   // 'rover' is in AssetManifest
const gameData = { generatedBy: 'tools/build_levels.mjs', missions, textures, facts: facts.facts, archiveNotes: facts.archiveNotes };
mkdirSync(join(ROOT, 'js/data'), { recursive: true });
writeFileSync(join(ROOT, 'js/data/GameData.js'),
    '/* AUTO-GENERATED by tools/build_levels.mjs - do not edit by hand. */\n' +
    `const GameData = Object.freeze(${JSON.stringify(gameData, null, 2)});\n`);
console.log(`\nwrote ${Object.keys(levels).length} levels + js/data/GameData.js`);
